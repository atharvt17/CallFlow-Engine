"""Generate ``reports/latency_calibration.md`` (M1-T06 deliverable).

Run explicitly — never as a side effect of the test suite:

    make calibration-report
    python -m tools.calibration_report

The test suite asserts the same bands (:mod:`tests.contract.test_latency_calibration`)
but is read-only, so a routine `pytest -q` leaves the working tree untouched.
Statistical measurements fluctuate run to run by design, which is why the
report is refreshed intentionally rather than on every execution.

Targets, bands and the sampler configuration are defined **here** and imported
by the test module, so the artifact and the assertions can never disagree
about what PASS means (and the dependency points tests → tool, never the
reverse). Exits non-zero if any band fails, so a refresh also re-verifies the
shipped sigma.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from mock.latency import percentiles, sample_latency_ms

# Shipped sampler defaults (SPECS §4 / Appendix B). No sigma tuning is needed:
# these targets pass at sigma=0.62.
MU = 5.7
SIGMA = 0.62
N_SAMPLER = 50_000

# SPECS §4: normative targets and calibration bands (sized for sampling noise).
TARGETS: dict[str, tuple[float, float]] = {
    "p50": (300.0, 0.10),
    "p90": (700.0, 0.15),
    "p99": (1200.0, 0.25),
}

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "reports" / "latency_calibration.md"


def band_verdict(measured: float, target: float, band: float) -> str:
    """PASS/FAIL for one percentile (shared with the test suite)."""
    return "PASS" if target * (1 - band) <= measured <= target * (1 + band) else "FAIL"


def measure(n: int = N_SAMPLER) -> tuple[dict[str, float], dict[str, str]]:
    """Sample the shipped lognormal and score it against the SPECS §4 bands."""
    samples = [sample_latency_ms(MU, SIGMA) for _ in range(n)]
    p50, p90, p99 = percentiles(samples, [0.5, 0.9, 0.99])
    measured = {"p50": p50, "p90": p90, "p99": p99}
    verdicts = {name: band_verdict(value, *TARGETS[name]) for name, value in measured.items()}
    return measured, verdicts


def render(measured: dict[str, float], verdicts: dict[str, str], *, n: int) -> str:
    lines = [
        "# Latency calibration — Appendix B targets vs measured",
        "",
        f"Sampler: n={n:,}, mu={MU}, sigma={SIGMA} (generated by",
        "`make calibration-report` → `tools/calibration_report.py`; refresh",
        "this file intentionally rather than on every test run).",
        "",
        "| percentile | measured (ms) | target (ms) | band | verdict |",
        "|---|---|---|---|---|",
    ]
    for name, (target, band) in TARGETS.items():
        lines.append(
            f"| {name} | {measured[name]:.1f} | {target:g} | ±{band * 100:.0f}% "
            f"| {verdicts[name]} |"
        )
    lines += [
        "",
        "Shipped default `LATENCY_SIGMA=0.62` (mu=5.7) — the calibrated",
        "approximation sanctioned by Appendix B's \"adjust sigma if needed\"",
        "sentence. `tests/contract/test_latency_calibration.py` asserts these",
        "bands on every run (read-only) and verifies endpoint wiring",
        "separately by ratio checks (p90/p50 ≈ 2.214, p99/p50 ≈ 4.231).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="report path")
    parser.add_argument("--n", type=int, default=N_SAMPLER, help="sample count")
    args = parser.parse_args()

    measured, verdicts = measure(args.n)
    for name, value in measured.items():
        target, band = TARGETS[name]
        print(
            f"{name}: measured {value:.1f} ms vs target {target:g} "
            f"±{band * 100:.0f}% -> {verdicts[name]}"
        )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(measured, verdicts, n=args.n), encoding="utf-8")
    print(f"wrote {args.out}")

    failed = [name for name, verdict in verdicts.items() if verdict != "PASS"]
    if failed:
        print(f"FAIL — outside SPECS §4 bands: {', '.join(failed)} (tune sigma)")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
